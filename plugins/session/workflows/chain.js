// Verification-first (lib/verification.md): this flow runs where no oracle can decide, ladder
// level e. Where an executable check exists it is the oracle and this chain is not the route; the
// `test` argument only lets the evidence stage and the fixer use that check as a fact.
//
// The four stages of idea 3.6. Every decision between them — the hint cap, the grouping by place,
// the form of the chain, the two kinds of failure, the control run on the base version and what
