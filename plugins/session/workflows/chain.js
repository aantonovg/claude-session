// echoedWaits(text, vars): the waits of a tmux launch script that its own typed line already
// satisfies. tests/corp/launch.sh and tests/demo-game/launch.sh prove a mode skill loaded by typing
// a slash command with `tmux send-keys` and then polling the pane for a line of the reply. The pane
// holds the typed command too, so a wait pattern that a typed line matches returns before the skill
// answered and proves nothing. The poller of both scripts greps the last 20 non-blank lines of the
// pane, so not only the line typed last stands there: every `wait_for` is read against the last
// ECHO_WINDOW typed lines before it, and a hit names the latest of them the pattern matches. `$var`
// and `${var}` in a typed line are resolved from <vars>, the values the script uses, so a command
// assembled from a variable is read the way it reaches the pane. A wait with no typed line before it
// (the first prompt of the session) is no hit.
const ECHO_WINDOW = 20 // the pane window the poller of those scripts reads, in non-blank lines
function echoedWaits(text, vars) {
  const v = vars || {}
  const subst = s => String(s).replace(/\$\{?([A-Za-z_][A-Za-z0-9_]*)\}?/g, (m0, name) =>
    Object.prototype.hasOwnProperty.call(v, name) ? String(v[name]) : m0)
  // the quote of a typed line is written \x22 and \x27: a literal quote inside a regexp of this
  // block opens a string for stripComments(), which reads no regexp literal, and the comment after
  // it would then be read as code
  // the typed text is the argument after the options, never the first quoted word of the line: a
  // pane target in quotes (`-t "$name"`) is no typed line, and reading from its quote gave a typed
  // text of `$name" "<the real command>` — junk that matched no pattern of a pane the session wrote.
  // `-t` takes its value, the other flags stand alone, and `--` ends the options.
  const SEND = /tmux send-keys\b(?:\s+-t\s+(?:[\x22][^\x22]*[\x22]|[\x27][^\x27]*[\x27]|[^\s\x22\x27]+)|\s+-[A-Za-z-]+|\s+--)*\s+([\x22\x27])(.*?)\1 Enter/
  const WAIT = /^\s*wait_for ([\x22\x27])(.*?)\1/
  const typed = []
  const hits = []
  String(text == null ? '' : text).split('\n').forEach((line, i) => {
    const sent = SEND.exec(line)
    if (sent) { typed.push(subst(sent[2])); if (typed.length > ECHO_WINDOW) typed.shift(); return }
    const w = WAIT.exec(line)
    if (!w || !typed.length) return
    const last = typed[typed.length - 1]
    let re
    try { re = new RegExp(w[2]) } catch (e) { hits.push({ line: i + 1, typed: last, re: w[2], why: 'no regexp' }); return }
    const echoed = typed.filter(t => re.test(t))
    if (echoed.length) hits.push({ line: i + 1, typed: echoed[echoed.length - 1], re: w[2], why: 'a typed line of the pane window matches' })
  })
  return hits
}

// hintVerdictHits(text): the places where <text> lets a hint decide by itself. A critic gives hints,
// never verdicts (idea 3.6): a claim is withdrawn only when a fact refutes it, and a hint no fact
// settles leaves the claim standing, marked as not checked. A text that makes a hint, a critique or
// a critic the subject of withdrawing, dropping or refuting turns the hint into a verdict, and a
// true fact of the object is then lost with no fact against it — which is exactly what an author
// reading a critique with no evidence step in front of it will do. The tests of this tree execute
// this over the role texts and over the flows that put a critique before an author.
// Only the subject shape counts: "drop the hint that nobody could settle" keeps the hint as the
// object and is no verdict, so the grammar of the sentence decides, never the vocabulary.
const HINT_SUBJECTS = ['hint', 'hints', 'critique', 'critiques', 'critic', 'critics', 'criticism']
const VERDICT_DONE = ['withdraws', 'withdrew', 'withdrawn', 'drops', 'dropped', 'refutes',
  'refuted', 'retracts', 'retracted', 'invalidates', 'invalidated', 'disproves', 'disproved',
  'rejects', 'rejected', 'removes', 'removed', 'overrules', 'overruled']
const VERDICT_BASE = ['withdraw', 'drop', 'refute', 'retract', 'invalidate', 'disprove', 'reject',
  'remove', 'overrule']
const VERDICT_MODALS = ['can', 'may', 'must', 'will', 'would', 'shall', 'should', 'could']
function hintVerdictHits(text) {
  const s = String(text == null ? '' : text).replace(/\s+/g, ' ')
  const subj = HINT_SUBJECTS.map(rxEsc).join('|')
  const done = VERDICT_DONE.map(rxEsc).join('|')
  const base = VERDICT_BASE.map(rxEsc).join('|')
  const modal = VERDICT_MODALS.map(rxEsc).join('|')
  const adv = '(?:[a-z]+ly |already |alone |then |also )?'
  const parts = [
    `\\b(?:${subj}) ${adv}(?:${done})\\b`, // "the critique withdraws a fact"
    `\\b(?:${subj}) (?:${modal}) ${adv}(?:${base})\\b`, // "a hint may drop a claim"
    // the same verdict written the other way round: "withdrawn per the critique". The preposition
    // `against` is no part of the list: "a fact settles it against the hint" is the right order,
    // the fact deciding and the hint decided.
    `\\b(?:${done})\\b[^.;!?]{0,24}?\\b(?:per|by|on|after) (?:the |a |any )?(?:${subj})\\b`,
  ]
  const re = new RegExp(parts.join('|'), 'gi')
  const hits = []
  let m
  while ((m = re.exec(s)) !== null) hits.push(m[0])
  return hits
}

// agentTypesOf(src): every agentType a workflow script of a plugin launches, resolved as far as a
// reader can resolve it — the launch name at the call site, the const it stands for, or the static
// head of a template literal (`session:${roleAgent(role)}`), which names the prefix even when the
// name itself is decided at run time. tests/rebuild/agents.sh executes this instead of grepping
// `agentType: '...'`: the const form and the shorthand `{ agentType, phase }` carry no quoted name,
// so a grep over them inspects nothing and an agentType of a foreign prefix passes unseen.
// Every site of the code is reported, the shorthand `{ agentType, phase }` with no binding in the
// file among them: dropping it would hand the caller a launch as no site at all, so an agent name
// decided outside the file (a parameter, a destructured value) would reach no check. Such a site
// comes back with neither prefix nor name — unresolved, for the caller to reject. The scan runs
// over stripComments(src), so the word in a comment is no site and needs no such exception.
const RX_BIND = /(?:const|let|var)\s+([A-Za-z_$][\w$]*)\s*=\s*(?:'([^'\n]*)'|"([^"\n]*)"|`([^`]*)`)/g
const RX_SITE = /agentType\s*(?::\s*(?:'([^'\n]*)'|"([^"\n]*)"|`([^`]*)`|([A-Za-z_$][\w$]*)))?\s*(?=[,}])/g
function agentTypeParts(text) {
  const s = String(text == null ? '' : text)
  const cut = s.indexOf('${')
  const head = cut === -1 ? s : s.slice(0, cut)
  // a template literal with a substitution resolves to no whole name: its static head still names
  // the prefix, which is what says whose agent a launch asks for
  const whole = cut === -1 ? s : null
  const colon = head.indexOf(':')
  if (colon === -1) return { value: whole, prefix: null, name: whole }
  return { value: whole, prefix: head.slice(0, colon), name: whole === null ? null : whole.slice(colon + 1) }
}
// stripComments(src): the code of a script with every comment taken out and nothing else moved. A
// launch key named in a comment is no launch. Quotes and template literals are read as text, so a
// `//` inside a string stays code; a newline is kept, so a line number still means something.
function stripComments(src) {
  const s = String(src == null ? '' : src)
  let out = ''
  let i = 0
  let q = null // the open quote character, or null outside a string
  while (i < s.length) {
    const c = s[i]
    const d = s[i + 1]
    if (q) {
      if (c === '\\') { out += s.slice(i, i + 2); i += 2; continue }
      if (c === q) q = null
      out += c; i++; continue
    }
    if (c === "'" || c === '"' || c === '`') { q = c; out += c; i++; continue }
    if (c === '/' && d === '/') { while (i < s.length && s[i] !== '\n') i++; continue }
    if (c === '/' && d === '*') {
      const e = s.indexOf('*/', i + 2)
      const end = e === -1 ? s.length : e + 2
      out += s.slice(i, end).replace(/[^\n]/g, ' ')
      i = end
      continue
    }
    out += c; i++
  }
  return out
}
function agentTypesOf(src) {
  const s = stripComments(src)
  const binds = {}
  let m
  RX_BIND.lastIndex = 0
  while ((m = RX_BIND.exec(s)) !== null) {
    const v = m[2] !== undefined ? m[2] : m[3] !== undefined ? m[3] : m[4]
    if (binds[m[1]] === undefined) binds[m[1]] = v
  }
  const sites = []
  RX_SITE.lastIndex = 0
  while ((m = RX_SITE.exec(s)) !== null) {
    const lit = m[1] !== undefined ? m[1] : m[2] !== undefined ? m[2] : m[3]
    const id = m[4] !== undefined ? m[4] : (m[0].indexOf(':') === -1 ? 'agentType' : null)
    let expr
    let text
    if (lit !== undefined) { expr = lit; text = lit } else if (id) {
      expr = id
      text = binds[id]
      if (text === undefined) text = null // unresolved, never dropped
    } else continue
    const p = text === null || text === undefined
      ? { value: null, prefix: null, name: null }
      : agentTypeParts(text)
    sites.push({ expr, value: p.value, prefix: p.prefix, name: p.name })
  }
  const seen = {}
  return sites.filter(x => {
    const k = `${x.expr}|${x.prefix}|${x.name}`
    if (seen[k]) return false
    seen[k] = 1
    return true
  })
}

// bindClass(class, submodes): the class of one run; every stage asks it for its agent options.
