// `mode` is 'file' for every stage that writes its output, and 'text' for the one stage whose
// output is its return: the two are checked by different rules, and nothing else differs.
async function stage(role, job, phaseName, fields, shape, mode) {
  const agentType = `session:${roleAgent(role)}`
  // a stage that never started still names its output path: a caller that collected the paths of
  // the blocked runs too would hand the next stage a file nobody wrote
  if (!AGENTS.includes(agentType)) return { out: fields.out, ok: false, ret: '', blocked: blockedLine(`role ${role} names no tool-set agent of this flow: ${agentType}`) }
  const f = fillRole(role, fields)
  if (f.missed.length) return { out: fields.out, ok: false, ret: '', blocked: blockedLine(`role text of ${role} reads ${f.missed.join(' ')}, outside the argument shape`) }
  // an output only a reading could check gets a stronger author, one class step up (3.5 rule 2);
  // the code and the tests, which the oracle decides, stay on the cheapest slot the class allows
  const JOB = bindClass(roleClass(role, CLS), SUBS)
  const o = JOB.opts(roleSlot(role, SIZE), job, { agentType, phase: phaseName })
  // agent() throws as well as returns null: an exception here would escape the result builder and
  // end the run with no shape at all, so it becomes the blocked line of this stage
  const text = mode === 'text' ? textTail(shape) : tail(fields.out, agentType, shape)
  let r = null
  try {
    r = await agent(f.text + text, o)
  } catch (e) {
    r = blockedLine(`the ${job} stage threw: ${(e && e.message) || e}`)
  }
  const ret = String(r == null ? '' : r)
  // a stage that returns its output is checked on that return, by the same shared block: an empty
  // or blocked return is a gap of the run, never a stage that did its job
  if (mode === 'text') {
    const c = closureReport(r)
    return { out: null, label: o.label, ret, ok: c.ok, blocked: c.ok ? null : blockedLine(c.gap), report: c.report, gap: c.gap }
  }
  const v = outVerdict(r, fields.out)
  return { out: fields.out, label: o.label, ret, ok: v.ok, blocked: v.ok ? null : v.blocked }
}

